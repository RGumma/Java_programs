package javaprograms;

public class FindTheLargerNumber {

	public static void main(String[] args) {

		int arr[] = { 10, 20, 30 };

		for (int i = 0; i < arr.length; i++) {

			if (arr[i] > 25) {

				System.out.println("Large numbers found");
				break;

			} else {

				System.out.println("No Large numbers");

			}

		}

	}

}

